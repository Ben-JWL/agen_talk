#!/usr/bin/env python3
"""Build the pixel-dungeon sprites: `python art/atlas/build.py` writes ui/src/72-atlas.js from art/atlas/sprites.json.
`--check` writes nothing and fails when the committed file is stale. Stdlib only, deterministic, LF line endings.

Format: window.AT_ATLAS = { size: 16, sprites: { <name>: '<rrggbb...>|<256 chars>' } }; a pixel char is '.' (transparent)
or ALPHA[k] for palette colour k. See art/atlas/README.md for where the pixels come from (CC0)."""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.normpath(os.path.join(HERE, "..", "..", "ui", "src", "72-atlas.js"))
BUDGET = 96 * 1024
ALPHA = "0123456789abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ"

with open(os.path.join(HERE, "sprites.json"), encoding="utf-8") as f:
    src = json.load(f)
rows = []
for name in sorted(src):
    s = src[name]
    pal, px = s["pal"], s["px"]
    assert re.fullmatch(r"[a-z]+(\.[a-z]+)?(\.\d+)?", name), name
    assert re.fullmatch(r"(?:[0-9a-f]{6})+", pal) and len(px) == 256, name
    assert all(c == "." or ALPHA.index(c) < len(pal) // 6 for c in px), name
    rows.append("%s:'%s|%s'" % (json.dumps(name), pal, px))
js = ("/* ===== 72-atlas.js — GENERATED by art/atlas/build.py from art/atlas/sprites.json; do not edit.\n"
      "   16x16 sprites for the 픽셀 던전, taken from the Pixel Art Atlas (Angais, CC0 1.0): see art/atlas/README.md. ===== */\n"
      "window.AT_ATLAS = { size: 16, alpha: '%s', sprites: {\n%s\n} };\n" % (ALPHA, ",\n".join(rows)))
assert len(js.encode("utf-8")) <= BUDGET, len(js)
if "--check" in sys.argv:
    with open(OUT, encoding="utf-8", newline="") as f:
        if f.read().replace("\r\n", "\n") != js:
            sys.exit("ui/src/72-atlas.js is stale: run `python art/atlas/build.py`")
    print("72-atlas.js matches art/atlas/sprites.json (%d sprites, %d bytes)" % (len(rows), len(js)))
else:
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(js)
    print(OUT, len(rows), "sprites", len(js), "bytes")
