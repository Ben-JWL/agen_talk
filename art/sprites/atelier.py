# Mug inbetweens interpolate the authored contours as integer clusters. No filtering.
# The upper endpoint follows the cup while the lower endpoint stays at the shoulder/elbow.
def contour_between(a,b,t):
    pa,xa,ya,na=a[:4]; pb,xb,yb,nb=b[:4]
    ga,gb=pa.g,pb.g
    y0=round(ya+(yb-ya)*t); x0=round(xa+(xb-xa)*t)
    h=round(pa.h+(pb.h-pa.h)*t); w=max(pa.w,pb.w)
    rows=[]
    for y in range(h):
        ra=ga[round(y*(pa.h-1)/max(1,h-1))]
        rb=gb[round(y*(pb.h-1)/max(1,h-1))]
        aa=[x for x,c in enumerate(ra) if c!='.']; bb=[x for x,c in enumerate(rb) if c!='.']
        row=['.']*w
        if aa and bb:
            lo=round(min(aa)+(min(bb)-min(aa))*t); hi=round(max(aa)+(max(bb)-max(aa))*t)
            for x in range(lo,hi+1): row[x]='C'
            if y<2:
                for x in range(lo,hi+1): row[x]='D'
            elif hi-lo>=2:
                row[lo]='i'; row[hi]='g'
        rows.append(''.join(row))
    return A.sl(rows,x0,y0,na,sep=1,kx=.4,ky=.1)

for holds in (A.HOLD,J.HOLD):
    keys=sorted(holds)
    for lo,hi in zip(keys,keys[1:]):
        for k in range(lo+1,hi):
            holds[k]=contour_between(holds[lo],holds[hi],(k-lo)/(hi-lo))

