# Repaint sleeves with local creases at elbow and wrist. The original silhouette is retained.
def tailor(arm):
    p=arm[0]
    g=[r[:] for r in p.g]
    for y,row in enumerate(g):
        for x,c in enumerate(row):
            # Keep only isolated crease origins; avoid parallel striped sausage arms.
            if c=='=': row[x]='g'
            if c=='-' and y%3!=1: row[x]='C'
            if c=='+' and y%4 not in (0,1): row[x]='C'
    return (Part([''.join(r) for r in g],kx=.45,ky=.12,cast=1,sep=1,mode='plane'),*arm[1:])

for collection in (A.A,A.HOLD,J.A,J.HOLD):
    for name,arm in list(collection.items()): collection[name]=tailor(arm)

