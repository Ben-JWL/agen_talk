# ------------------------------------------------------------------ arms (absolute origin at body offset 0)
# Each arm: (Part, x0, y0) drawn as the screen-left arm; the right arm is its mirror about AXIS.
def arm(rows, x, y, **kw):
    kw.setdefault('kx', 0.7)
    kw.setdefault('ky', 0.15)
    kw.setdefault('edge', 0.7)
    kw.setdefault('cast', 1)
    kw.setdefault('sep', 1)
    return (Part(rows, **kw), x, y)


