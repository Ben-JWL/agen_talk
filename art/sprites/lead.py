def _extend(p, n=4):
    p.g += [p.g[-1][:] for _ in range(n)]
    p.h = len(p.g)
    p._cache = {}


for _p in (CL_TORSO, CX_TORSO, AG_TORSO):
    _extend(_p)


def _narrow(p, cols=(19, 3)):
    for c in cols:
        p.g = [r[:c] + r[c + 1:] for r in p.g]
    p.w = len(p.g[0])
    p._cache = {}


for _p in (CL_TORSO, CX_TORSO, AG_TORSO, CX_HOOD):
    _narrow(_p)
