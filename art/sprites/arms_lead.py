# v2 lead arms: sleeves with hand-placed folds + separate hand sprites.
# Sleeve marks: C cloth (plane-shaded: lit/shadow planes, no pillow edges), - crease, = deep crease,
# + fold highlight, D cuff, : cuff rib. A sleeve is drawn as the screen-left arm unless native 'R'/'N'.
# Tuple: (Part, x0, y0, native, [(hand, dx, dy), ...])
from core import Part
import hands as HN


def sl(rows, x, y, nat='L', hands=(), **kw):
    kw.setdefault('kx', 0.75)
    kw.setdefault('ky', 0.2)
    kw.setdefault('cast', 1)
    kw.setdefault('sep', 1)
    kw.setdefault('mode', 'plane')
    return (Part(rows, **kw), x, y, nat, list(hands))


