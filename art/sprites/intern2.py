# =============================================================== sleeves with folds + hands
def sl(rows, x, y, nat='L', hands=(), **kw):
    kw.setdefault('kx', 0.75)
    kw.setdefault('ky', 0.2)
    kw.setdefault('cast', 1)
    kw.setdefault('sep', 1)
    kw.setdefault('mode', 'plane')
    return (Part(rows, **kw), x, y, nat, list(hands))


